# Financial debate and vocational/near-adult stories should not appear in early primary school.
AGE_LIMITS = {'FAM01':(6,11),'FAM02':(16,17),'FAM03':(6,11),'FAM04':(12,17),
 'FAM05':(15,17),'FAM06':(16,17),'FAM07':(8,17),'FAM08':(6,17),
 'YOU01':(12,17),'YOU02':(16,17),'YOU03':(16,17),'YOU04':(15,17),
 'YOU05':(17,17),'YOU06':(12,17),'YOU07':(12,17),'YOU08':(17,17)}

def refine_childhood_events(events):
    index = {e['id']: e for e in events}
    for eid, (title, prompt, rows) in SCENES.items():
        event = index[eid]
        event.update(title=title, prompt=prompt)
        assert len(rows) == len(event['choices']), eid
        for choice, row in zip(event['choices'], rows):
            assert len(row) == len(choice['outcomes']) + 1, choice['id']
            choice['label'] = row[0]
            for outcome, text in zip(choice['outcomes'], row[1:]):
                outcome['text'] = text
    for eid, (low, high) in AGE_LIMITS.items():
        index[eid].update(age_min=low, age_max=high)
    purchase = index['MAIN02']['choices'][0]
    purchase['requirements'] = {'min_cash_yuan': 1, 'all': []}
    # One concrete purchase, paid once. Other branches still work with zero cash.
    for i, outcome in enumerate(purchase['outcomes']):
        outcome['effects'] = [e for e in outcome['effects'] if e['op'] != 'spend']
        if i == 0:
            outcome['effects'].insert(0, {'op': 'spend', 'amount_yuan': 1})
    for event in events:
        if event['age_max'] >= 18:
            continue
        for choice in event['choices']:
            for outcome in choice['outcomes']:
                effects = deepcopy(outcome['effects'])
                for effect in effects:
                    if effect['op'] != 'stat':
                        continue
                    # Learning at school is not professional work experience. Keep money,
                    # flags and delayed story edges intact; don't rewrite historical saves.
                    effect['delta'].pop('skill', None)
                    effect['delta'].pop('fame', None)
                    if event['age_max'] < 6:
                        effect['delta'].pop('academic', None)
                outcome['effects'] = [e for e in effects if e['op'] != 'stat' or e['delta']]

if __name__ == '__main__':
    import json
    from pathlib import Path
    path = Path(__file__).resolve().parents[1] / 'data/events.json'
    catalog = json.loads(path.read_text())
    refine_childhood_events(catalog['events'])
    path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')
