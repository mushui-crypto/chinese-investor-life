def expand_random_events(events):
    index={e['id']:e for e in events}
    for eid,rows in GROWTH_COPY.items():
        for choice,row in zip(index[eid]['choices'],rows):
            choice['label']=row[0]
            for i,outcome in enumerate(choice['outcomes']):
                outcome['text']=row[min(i+1,len(row)-1)]
    for age,title,prompt,rows in NEW_GROWTH:
        eid=f'AGE{age:02d}C'
        if eid in index: continue
        e=deepcopy(index[f'AGE{age:02d}A'])
        e.update(id=eid,title=title,prompt=prompt)
        for n,(choice,row) in enumerate(zip(e['choices'],rows),1):
            choice.update(id=f'{eid}_{n}',label=row[0])
            for j,outcome in enumerate(choice['outcomes'],1):
                outcome.update(id=f'{eid}_{n}_{j}',text=row[min(j,len(row)-1)])
        events.append(e)

